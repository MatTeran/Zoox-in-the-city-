import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Copies Vite `dist/` into expo-app/assets/www so Expo WebView can demo offline.
 * Also writes a tiny bridge HTML that WebView can load via require() on web,
 * and documents the folder for native file URI loading.
 */

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const distDir = join(root, 'dist');
const targetDir = join(root, 'expo-app', 'assets', 'www');

if (!existsSync(distDir)) {
  console.error('Missing dist/. Run `npm run build` first.');
  process.exit(1);
}

rmSync(targetDir, { recursive: true, force: true });
mkdirSync(targetDir, { recursive: true });
cpSync(distDir, targetDir, { recursive: true });

// Ensure relative asset paths remain valid inside the copied bundle.
const indexPath = join(targetDir, 'index.html');
if (existsSync(indexPath)) {
  const html = readFileSync(indexPath, 'utf8');
  writeFileSync(indexPath, html, 'utf8');
}

writeFileSync(
  join(targetDir, 'README.md'),
  [
    '# Bundled Phaser build for Expo',
    '',
    'Generated by `npm run sync:expo-web` from the repo root.',
    'Do not edit by hand — re-run the sync script after game changes.',
    '',
  ].join('\n'),
  'utf8',
);

console.log(`Synced ${distDir} → ${targetDir}`);
